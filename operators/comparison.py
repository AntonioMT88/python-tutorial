# Comparison Operator
"""
Equal to:                   ==
Not equal to:               !=
Less than:                  <
Greater than:               >
Less than or equal to:      <=
Greater than or equal to:   >=
"""

a = 10
b = 3

print("Equal to")
print(a == b)

print("Not equal to")
print(a != b)

print("Less than")
print(a < b)

print("Greater than")
print(a > b)

print("Less than or equal to")
print(a <= b)

print("Greater than or equal to")
print(a >= b)



