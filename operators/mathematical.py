# Mathematical Operator
"""
Sum             -> +
Subtraction     -> -
Multiplication  -> *
Division        -> / or //
Exponentiation  -> **
Mod             -> %
"""

a = 10
b = 3

print("Sum Operation")
print(a + b)

print("Subtraction Operation")
print(a - b)

print("Multiplication Operation")
print(a * b)

print("Division Operation")
print(a / b)
print(a // b)

print("Exponentiation Operation")
print(a ** b)

print("Mod Operation")
print(a % b)



